package com.wangc.bill.reference;

/** Original DayInfo's two inclusive millisecond boundaries. */
public final class OriginalDayInfo {
    private long minDay,maxDay;
    public long getMinDay(){return minDay;}
    public void setMinDay(long value){minDay=value;}
    public long getMaxDay(){return maxDay;}
    public void setMaxDay(long value){maxDay=value;}
}
